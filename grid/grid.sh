#!/usr/bin/env bash
# GRID: unified entry for benchmark methods, evaluation, and individual-matching ABM.
set -euo pipefail
umask 077
export PYTHONDONTWRITEBYTECODE=1

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)

# Use the same foreground logger as LE8, once for the whole module sequence.
# Keep help, command previews and a standalone Shiny server directly visible.
export SCRIPT_LOG_DIR=${SCRIPT_LOG_DIR:-/tmp/grid-logs/runs}
_grid_console_bypass=0
for _grid_arg in "$@"; do
	case $_grid_arg in
		-h|--help|help|--python-help|--dry-run|--dry-run=*|shiny) _grid_console_bypass=1 ;;
	esac
done
if [[ ${SCRIPT_CONSOLE_ACTIVE:-0} != 1 && ${SCRIPT_VERBOSE:-0} != 1 && $_grid_console_bypass == 0 ]]; then
	exec python3 "$ROOT/../0f/console_run.py" --script "$ROOT/grid.sh" -- "$@"
fi
unset _grid_console_bypass _grid_arg

die() { printf 'ERROR: %s\n' "$*" >&2; exit 2; }
need_value() { [[ $# -ge 2 && -n $2 && $2 != --* ]] || die "Missing value for $1"; }
validate_traits() {
	[[ $1 =~ ^(height|ldl|t2dm)(,(height|ldl|t2dm))*$ ]] || die 'Use unique traits from height,ldl,t2dm'
	local trait
	local -a traits
	local -A seen=()
	IFS=, read -r -a traits <<<"$1"
	for trait in "${traits[@]}"; do
		[[ -z ${seen[$trait]+present} ]] || die "Repeated trait: $trait"
		seen[$trait]=1
	done
}

usage() {
	cat <<'HELP'
GRID — Genetic Risk based on Individual Distance

Modules:
  prsformer  Reproduce PRSformer; automatically prepare its shared GRID roster.
  abm        Run the innovative ABM method: prepare, features, fit and publish.
  final      Evaluate available CSx, Disco, PRSformer and ABM results and plot performance.
  shiny      Browse the five-module summary generated by final (default localhost:3839).

Example usage (WSL; default traits: height,ldl,t2dm):
  cd /mnt/d/scripts/grid

  # Upstream preparation; completed matching results are reused.
  ./0.pca.sh
  ./1.csx.sh                 # Auto CPU/CUDA; --backend cpu forces CPU.
  ./2.disco.sh

  # Main workflow: PRSformer -> ABM -> final summary -> Shiny.
  # Fresh model run; existing prepared inputs are reused after validation.
  ./grid.sh prsformer,abm,final,shiny

  # Optional: select traits, or inspect the complete sequence without running it.
  ./grid.sh prsformer,abm,final,shiny --traits height,ldl,t2dm --dry-run

  # After training is already complete, refresh final and open the webpage.
  ./grid.sh final,shiny
  # Resume an interrupted PRSformer run with unchanged inputs/settings/code.
  ./grid.sh prsformer --prsformer-arg --resume
  # Summarize existing reports only, without recalculating comparisons.
  ./grid.sh final --summary-only

Controls:
  --traits LIST      Default height,ldl,t2dm.
  --check            Validate inputs without fitting.
  --dry-run          Print commands without running analysis.
  --wait-lock        For one module, wait for another run using its cache.
  --help             Show module help.
  --python-help      Show advanced ABM options.

Logging:
  Screen shows stages, GPU checks and concise progress; full logs: /tmp/grid-logs/runs.
  SCRIPT_LOG_DIR=DIR changes the log directory; SCRIPT_VERBOSE=1 shows all output.

Notes:
  * Five method folders under /mnt/d/analysis/grid:
    pca/, csx/, disco/, prsformer/, abm/. Combined reports and Shiny data: final/.
    PCA/Disco permanent individual-ID data stay under /mnt/d/data/ukb/.
  * Comma-separated modules run in the listed order and stop on the first error.
    Shared sequence options: --traits, --check, --dry-run. For method-specific
    options, run the modules separately. --traits selects analysis traits;
    Shiny displays the resulting final snapshot and must be last in a sequence.
    Shiny stays in the foreground at http://127.0.0.1:3839; Ctrl+C stops the server.
  * PRSformer saves cache/ and run/ (checkpoints/history) under OUTPUT_ROOT/prsformer from the start.
    To retain an earlier run when retraining, select --prsformer-run-dir in a single-module call.
  * ABM runs its complete workflow with no --stage option needed.
  * final uses saved PRSformer/ABM predictions; it never retrains those models.
    Learned methods require identical outer test registries and predictions for
    every test participant with an observed trait endpoint.
    Legacy/custom intersection requires --allow-test-intersection TRUE in final.
    After ABM finishes, retry evaluation with grid.sh final to avoid refitting ABM.
    Baseline-only evaluation retains the original Yeval cross-validation workflow.
  * Skip prsformer when a completed benchmark uses the same frozen GRID test roster.
  * After the GRID roster is frozen, ABM and PRSformer use separate cache locks.
    PRSformer keeps its own roster snapshot; concurrent training shares GPU resources.
  * CSx cache reuse still republishes scores, which may trigger Disco recalculation.
  * ABM refits and overwrites its outputs by default; --no-replace changes this.
    Existing cohort IDs, families and test split remain frozen even with --replace.
    Use separate cache/output roots when intentionally changing the cohort.

HELP
}

MODULE=abm
if (($#)); then
	case $1 in
		-h|--help|help) usage; exit 0 ;;
		--*) ;;
		*) MODULE=$1; shift ;;
	esac
fi

# Validate the complete sequence before starting any expensive model run.
if [[ $MODULE == *,* ]]; then
	[[ $MODULE =~ ^(prsformer|abm|final|shiny)(,(prsformer|abm|final|shiny))+$ ]] || die "Invalid module sequence: $MODULE (use prsformer, abm, final, shiny)"
	IFS=, read -r -a MODULES <<<"$MODULE"
	[[ ,$MODULE, != *,shiny,* || ${MODULES[-1]} == shiny ]] || die 'Shiny must be last in a module sequence'
	declare -A SEEN_MODULES=()
	for module in "${MODULES[@]}"; do
		[[ -z ${SEEN_MODULES[$module]+present} ]] || die "Repeated module: $module"
		SEEN_MODULES[$module]=1
	done
	SEQUENCE_ARGS=()
	SEQUENCE_DRY_RUN=FALSE
	while (($#)); do
		case $1 in --*=*) set -- "${1%%=*}" "${1#*=}" "${@:2}" ;; esac
		case $1 in
			-h|--help|help) usage; exit 0 ;;
			--trait|--traits) need_value "$@"; validate_traits "$2"; SEQUENCE_ARGS+=(--traits "$2"); shift 2 ;;
			--check) SEQUENCE_ARGS+=(--check); shift ;;
			--dry-run)
				shift
				SEQUENCE_DRY_RUN=TRUE
				if (($#)); then
					case ${1^^} in TRUE|FALSE) SEQUENCE_DRY_RUN=${1^^}; shift ;; esac
				fi
				;;
			*) die "Option $1 is not shared by a module sequence; run modules separately for method-specific options" ;;
		esac
	done
	[[ $SEQUENCE_DRY_RUN == FALSE ]] || SEQUENCE_ARGS+=(--dry-run)
	for module in "${MODULES[@]}"; do
		printf '\nMODULE %s\n' "$module"
		if [[ $module == shiny ]]; then
			SHINY_SEQUENCE_ARGS=()
			for arg in "${SEQUENCE_ARGS[@]}"; do
				case $arg in --check|--dry-run) SHINY_SEQUENCE_ARGS+=("$arg") ;; esac
			done
			bash "$ROOT/grid.sh" shiny "${SHINY_SEQUENCE_ARGS[@]}" || exit "$?"
		else
			bash "$ROOT/grid.sh" "$module" "${SEQUENCE_ARGS[@]}" || exit "$?"
		fi
	done
	exit 0
fi

case "$MODULE" in
	-h|--help|help) usage; exit 0 ;;
	shiny)
		exec bash "$ROOT/f/shiny.sh" "$@"
		;;
	final)
		[[ -f "$ROOT/f/final.sh" ]] || die "Missing $ROOT/f/final.sh; apply the update package first"
		exec bash "$ROOT/f/final.sh" "$@"
		;;
	abm|prsformer) ;;
	*) die "Unknown module: $MODULE (see: bash grid.sh help)" ;;
esac

# One public PRSformer entry. Independent-cohort mode preserves existing
# training caches/checkpoints and runtime checks without creating a second script.
if [[ $MODULE == prsformer ]]; then
	PRS_STANDALONE=FALSE
	PRS_MODULE_ARGS=()
	for arg in "$@"; do
		if [[ $arg == --standalone ]]; then
			PRS_STANDALONE=TRUE
		else
			PRS_MODULE_ARGS+=("$arg")
		fi
	done
	if [[ $PRS_STANDALONE == TRUE ]]; then
		exec bash "$ROOT/f/prsformer.sh" "${PRS_MODULE_ARGS[@]}"
	fi
	for arg in "$@"; do
		case $arg in -h|--help|help)
			cat <<'HELP'
GRID PRSformer — one public entry: bash grid.sh prsformer

Default: reuse the frozen GRID cohort; prepare it only when no roster exists.
Default traits: height,ldl,t2dm; default device: cuda.
  cd /mnt/d/scripts/grid
  bash grid.sh prsformer

Optional: republish reports from an existing shared-split run without training.
  bash grid.sh prsformer --prsformer-mode report --prsformer-replace TRUE

Common options:
  --cache-dir DIR       GRID cache containing split.rds (default /tmp/grid-cache/grid).
                        A published OUTROOT/grid.split.rds can also supply the roster.
  --prsformer-cache-dir DIR  Prepared inputs (default PRSFORMER_ROOT/prsformer/cache).
  --prsformer-run-dir DIR    Checkpoints/history (default PRSFORMER_ROOT/prsformer/run).
  --out-root DIR        ABM report root (default /mnt/d/analysis/grid/abm).
  --prsformer-root DIR  Parent of the prsformer output folder (default parent of OUTROOT).
  --wait-lock          Wait for another run of the same module/cache.
  --prsformer-OPTION VALUE  Model options, e.g. --prsformer-python PATH,
                            --prsformer-epochs 30, --prsformer-mode train.
  --prsformer-arg ARG   One exact model token, e.g. --prsformer-arg --resume.
  --check / --dry-run   Validate or print the shared-cohort invocation.

Screen output shows stages, GPU checks and concise progress. Full logs are saved
under /tmp/grid-logs/runs (override SCRIPT_LOG_DIR); SCRIPT_VERBOSE=1 shows all output.

PRSformer stores an unchanged roster snapshot under its own CACHE/roster directory.
It requires the entire GRID cohort and will fail if phenotype/genotype alignment
drops participants. ABM features and caches are preserved. After training:
  bash grid.sh final
Or train and compare in order:
  bash grid.sh prsformer,final

Existing independent 60/20/20 runs, custom cohorts and runtime-only checks:
  bash grid.sh prsformer --standalone --help
  bash grid.sh prsformer --standalone --check-runtime
  bash grid.sh prsformer --standalone --mode report --replace
In --standalone mode, use ordinary model flags (--python, --device, --mode, etc.).
Both modes save prepared inputs and checkpoints under the prsformer output folder.
HELP
			exit 0 ;;
		esac
	done
fi

PYTHON=${GRID_PYTHON:-python3}
PYTHON_EXPLICIT=FALSE
[[ -z ${GRID_PYTHON:-} ]] || PYTHON_EXPLICIT=TRUE
CACHE_DIR=/tmp/grid-cache/grid
OUT_ROOT=/mnt/d/analysis/grid/abm
PRSFORMER_ROOT=
PRS_CACHE_DIR=
STAGE=all
TRAITS=height,ldl,t2dm
REPLACE=TRUE
WAIT_LOCK=FALSE
SHARED_SEED=20260904
DRY_RUN=FALSE
PYTHON_HELP=FALSE
RUN_LOG=
GRID_ARGS=()
PRS_SHARED=()
PRS_ARGS=()

while (($#)); do
	case $1 in --*=*) set -- "${1%%=*}" "${1#*=}" "${@:2}" ;; esac
	case $1 in
		-h|--help|help) usage; exit 0 ;;
		--python-help) PYTHON_HELP=TRUE; shift ;;
		--python) need_value "$@"; PYTHON=$2; PYTHON_EXPLICIT=TRUE; shift 2 ;;
		--replace) REPLACE=TRUE; shift ;;
		--no-replace) REPLACE=FALSE; shift ;;
		--wait-lock) WAIT_LOCK=TRUE; shift ;;
		--check) STAGE=check; shift ;;
		--check-device) STAGE=check; GRID_ARGS+=(--check-device); shift ;;
		--stage)
			need_value "$@"
			STAGE=$2
			[[ $STAGE != features ]] || STAGE=evolution
			shift 2
			;;
		--cache-dir) need_value "$@"; CACHE_DIR=$2; shift 2 ;;
		--out-root) need_value "$@"; OUT_ROOT=$2; shift 2 ;;
		--trait|--traits) need_value "$@"; TRAITS=$2; shift 2 ;;
		--prsformer-root) need_value "$@"; PRSFORMER_ROOT=$2; shift 2 ;;
		--prsformer-cache-dir) need_value "$@"; PRS_CACHE_DIR=$2; shift 2 ;;
		--dry-run)
			flag_value=TRUE
			shift
			if (($#)); then
				case ${1^^} in TRUE|FALSE) flag_value=${1^^}; shift ;; esac
			fi
			DRY_RUN=$flag_value
			;;
		--prsformer-arg)
			[[ $# -ge 2 && -n $2 ]] || die '--prsformer-arg requires one exact token'
			PRS_ARGS+=("$2")
			shift 2
			;;
		--prsformer-*)
			need_value "$@"
			PRS_ARGS+=("--${1#--prsformer-}" "$2")
			shift 2
			;;
		--seed) need_value "$@"; SHARED_SEED=$2; GRID_ARGS+=("$1" "$2"); PRS_SHARED+=("$1" "$2"); shift 2 ;;
		--pheno-file|--ancestry-file|--group-col|--dir-gen|--covariates|--height-col|--ldl-col|--t2dm-col|--chrs|--remove)
			need_value "$@"; GRID_ARGS+=("$1" "$2"); PRS_SHARED+=("$1" "$2"); shift 2 ;;
		--snpinfo)
			need_value "$@"; GRID_ARGS+=("$1" "$2"); PRS_SHARED+=(--snp-list "$2"); shift 2 ;;
		*) GRID_ARGS+=("$1"); shift ;;
	esac
done

validate_traits "$TRAITS"
case $STAGE in prepare|evolution|fit|predict|report|all|check) ;;
	*) die "Unknown ABM --stage: $STAGE" ;;
esac
[[ $MODULE != prsformer || $STAGE == all || $STAGE == check ]] || die 'For PRSformer stages, use --prsformer-mode prepare/train/predict/report'
[[ -n $CACHE_DIR && $CACHE_DIR != / ]] || die 'Use a dedicated non-root --cache-dir'
[[ -n $OUT_ROOT && $OUT_ROOT != / ]] || die 'Use a dedicated non-root --out-root'
[[ -n $PRSFORMER_ROOT ]] || PRSFORMER_ROOT="$(dirname -- "$OUT_ROOT")"
[[ -n $PRS_CACHE_DIR ]] || PRS_CACHE_DIR="$PRSFORMER_ROOT/prsformer/cache"
PRS_ROSTER_DIR="$PRS_CACHE_DIR/roster"

if [[ $DRY_RUN == FALSE ]]; then
	if [[ $PYTHON_EXPLICIT == FALSE ]]; then
		CONDA_INIT="$HOME/miniforge3/etc/profile.d/conda.sh"
		[[ -f $CONDA_INIT ]] || CONDA_INIT="$HOME/anaconda3/etc/profile.d/conda.sh"
		[[ -f $CONDA_INIT ]] || die 'Conda initialization script unavailable; install Miniforge/Conda first'
		set +u
		# shellcheck disable=SC1090 # The installed Conda root is resolved above.
		if source "$CONDA_INIT" && conda activate "${GRID_ENV_NAME:-grid}"; then CONDA_STATUS=0; else CONDA_STATUS=$?; fi
		set -u
		((CONDA_STATUS == 0)) || die 'Could not activate Conda environment grid; run install_grid.sh'
	fi
	PYTHON_COMMAND=$(command -v "$PYTHON") || die "Python unavailable: $PYTHON"
	PYTHON_DIRECTORY=$(cd -- "$(dirname -- "$PYTHON_COMMAND")" && pwd -P)
	PYTHON="$PYTHON_DIRECTORY/$(basename -- "$PYTHON_COMMAND")"
	export PATH="$PYTHON_DIRECTORY:$PATH"
fi

run_command() {
	printf 'RUN '; printf '%q ' "$@"; printf '\n'
	[[ $DRY_RUN == FALSE ]] || return 0
	if [[ -n $RUN_LOG ]]; then "$@" 2>&1 | tee -a "$RUN_LOG"; else "$@"; fi
}

if [[ $PYTHON_HELP == TRUE ]]; then
	run_command "$PYTHON" "$ROOT/f/main.py" --help
	exit 0
fi

run_abm_stage() {
	local replace_args=()
	[[ $REPLACE == FALSE ]] || replace_args=(--replace)
	run_command "$PYTHON" "$ROOT/f/main.py" --stage "$1" \
		--cache-dir "$CACHE_DIR" --out-root "$OUT_ROOT" --traits "$TRAITS" \
		--prsformer-root "$PRSFORMER_ROOT" --publish-only "${replace_args[@]}" "${GRID_ARGS[@]}"
}

run_prsformer() {
	local path
	local check_args=()
	[[ $STAGE != check ]] || check_args=(--check)
	if [[ $DRY_RUN == FALSE ]]; then
		for path in common.keep families.tsv.gz prsformer.split.tsv.gz; do
			[[ -s $PRS_ROSTER_DIR/$path ]] || die "Missing shared roster $PRS_ROSTER_DIR/$path; run 'grid.sh prsformer' to prepare it"
		done
	fi
	run_command bash "$ROOT/f/prsformer.sh" \
		--train-fraction 0.4 --validation-fraction 0.1 \
		"${PRS_ARGS[@]}" "${PRS_SHARED[@]}" "${check_args[@]}" --traits "$TRAITS" \
		--cache-dir "$PRS_CACHE_DIR" --keep "$PRS_ROSTER_DIR/common.keep" \
		--split-file "$PRS_ROSTER_DIR/prsformer.split.tsv.gz" \
		--split-group-file "$PRS_ROSTER_DIR/families.tsv.gz" \
		--require-shared-cohort \
		--output-root "$PRSFORMER_ROOT" --score-dir "$PRSFORMER_ROOT/prsformer/scores"
}

acquire_lock() {
	local path=$1
	exec {module_lock}>"$path"
	if [[ $WAIT_LOCK == TRUE ]]; then
		printf 'WAIT for exclusive module cache: %s\n' "$path"
		flock "$module_lock"
	else
		flock -n "$module_lock" || die "Another run is using $path; use --wait-lock to queue this run"
	fi
}

if [[ $DRY_RUN == FALSE ]]; then
	if [[ $MODULE != prsformer ]]; then
		command -v "$PYTHON" >/dev/null 2>&1 || die "Python unavailable: $PYTHON"
		[[ -f $ROOT/f/main.py ]] || die "Missing GRID implementation: $ROOT/f/main.py"
	fi
	if [[ $STAGE != check ]]; then
		command -v flock >/dev/null 2>&1 || die 'flock is required'
		mkdir -p -- "$CACHE_DIR"
		if [[ $MODULE == prsformer ]]; then
			mkdir -p -- "$PRS_CACHE_DIR"
			acquire_lock "$PRS_CACHE_DIR/grid.wrapper.lock"
		else
			acquire_lock "$CACHE_DIR/grid.lock"
		fi
		mkdir -p -- "$CACHE_DIR/logs"
		RUN_LOG=$(mktemp "$CACHE_DIR/logs/grid.$(date -u +%Y%m%dT%H%M%SZ).XXXXXX.log")
		printf 'LOG %s\n' "$RUN_LOG"
	fi
fi

if [[ $MODULE == prsformer ]]; then
	# Reuse frozen IDs and preserve all ABM features and input timestamps. Rewriting
	# the roster on every invocation invalidates PRSformer cache/resume signatures.
	PRS_MODE=all
	for ((i=0; i<${#PRS_ARGS[@]}; i++)); do
		[[ ${PRS_ARGS[$i]} != --mode ]] || PRS_MODE=${PRS_ARGS[$((i+1))]}
	done
	if [[ $STAGE != check && ( $PRS_MODE == all || $PRS_MODE == prepare ) && ! -s $CACHE_DIR/split.rds && ! -s $OUT_ROOT/grid.split.rds ]]; then
		if [[ $DRY_RUN == FALSE ]]; then
			exec {prepare_lock}>"$CACHE_DIR/grid.lock"
			flock -n "$prepare_lock" || die "ABM is preparing the initial roster; retry after its preparation finishes"
		fi
		if [[ ! -s $CACHE_DIR/split.rds && ! -s $OUT_ROOT/grid.split.rds ]]; then run_abm_stage prepare; fi
		if [[ $DRY_RUN == FALSE ]]; then flock -u "$prepare_lock"; exec {prepare_lock}>&-; fi
	fi
	ROSTER_ARGS=(--cache-dir "$CACHE_DIR" --grid-split "$OUT_ROOT/grid.split.rds" --seed "$SHARED_SEED")
	if [[ $STAGE == check ]]; then
		if [[ -d $PRS_ROSTER_DIR ]]; then
			ROSTER_ARGS+=(--check)
		elif [[ $DRY_RUN == FALSE ]]; then
			PRS_ROSTER_DIR=$(mktemp -d /tmp/grid-prsformer-roster-check.XXXXXX)
			trap 'rm -rf -- "$PRS_ROSTER_DIR"' EXIT
		fi
	fi
	ROSTER_ARGS+=(--roster-dir "$PRS_ROSTER_DIR")
	run_command "$PYTHON" "$ROOT/f/prsformer.py" shared-roster "${ROSTER_ARGS[@]}"
	run_prsformer
else
	run_abm_stage "$STAGE"
fi
