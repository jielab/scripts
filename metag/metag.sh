#!/usr/bin/env bash

# Public directory options use --dir-XXX; legacy spellings remain compatible.
if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    source /mnt/d/scripts/0f/cli_dirs.sh
    script_directory_args "$(realpath -- "${BASH_SOURCE[0]}")" "$@"
    set -- "${SCRIPT_DIRECTORY_ARGS[@]}"
    unset SCRIPT_DIRECTORY_ARGS
fi
# Public entry point; runtime modules live in f/.
set -euo pipefail
# Analysis must use the logging runner, including the no-argument full workflow.
# The shared passthrough runner deliberately does not write a console log.
if [[ ${SCRIPT_CONSOLE_ACTIVE:-0} != 1 ]]; then
    case " $* " in
        *' --help '*|*' -h '*|*' help '*|*' --dry-run '*) ;;
        *) exec python3 /mnt/d/scripts/0f/console_run.py --script "${BASH_SOURCE[0]}" -- "$@" ;;
    esac
fi
source /mnt/d/scripts/0f/console.sh
export PYTHONDONTWRITEBYTECODE=1
METAG_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

usage() {
	cat <<'HELP'
Modules:
    split       Inventory inputs; prepare/reuse references; split by species
                   Trust external MD5 checks; no FASTQ QC pre-scan
                   Stop on missing, corrupt or malformed inputs while reading
                   Keep unresolved reads in each run's split.bad; preserve read pairs
                   Finish and verify each dataset; retain raw FASTQ by default for archiving
                   Write species/virus summaries, plots and split.done after success
    prep_ref    Prepare/reuse references; audit; clean reference FASTA and .fna.gz
    reference-clean  Validate a completed reference and preview cleanup (--execute to delete)

    Default: input inventory -> reference libraries/index/audit -> split.
    metag.conf: delete_raw_after_split = FALSE; set TRUE to enable raw cleanup.
    raw.bad and a raw QC lock are not created.
    Summaries are generated by split; no separate summary step is required.
    Without a module, run the complete workflow. Completed runs are checked and reused.
    Advanced/reference-only commands are documented in 0.README.md.

Main options:
    --dir-fastq DIR       FASTQ dataset folders [/mnt/f/metag/raw]
    --dir-out DIR         Input manifests, logs and summaries [/mnt/d/analysis/metag]
    --dir-split DIR       Split FASTQ and dataset receipts [raw sibling: /mnt/f/metag/split]
    --dir-annot DIR       Shared references [/mnt/f/annot/kraken2_ictv]
    --dat-list CSV        Dataset folder names [all non-symlink folders in --dir-fastq]
    --threads N           Build / total Kraken2 classification threads [16]
    --split-jobs N        Parallel split samples; shared database mapping [4]
    --keep-assignments    Also write per-read assignment TSV.gz [off]
    --delete-raw-after-split TRUE|FALSE  Override metag.conf for this invocation
    --download-threads N  Reference download threads [8]
    --mask-jobs N         Parallel reference genomes, independently resumable [2]
    --masker-threads N    Threads per reference masker [1]
    --prepare-memory-gb N Reference preparation RAM cap [12]; swap cap 1 GiB
    --max-db-gb N         Build hash-table cap in GiB [24]
    --classification-mode full|quick  Search both mates completely or early-stop screening [full]
    --confidence FLOAT    Kraken2 confidence [0.1]
    --hit-groups N        Minimum hit groups [3]
    --memory-mapping     Memory-map the classification database
    --dry-run            Print planned commands without executing
    <module> --help       Module-specific options
    -h, --help            Help; paths, prerequisites and notes: 0.README.md

Example:
    ./metag.sh --dir-fastq /mnt/f/metag/raw --dir-annot /mnt/f/annot/kraken2_ictv --dir-out /mnt/d/analysis/metag --threads 16
    ./metag.sh

HELP
}

case "${1:-}" in
  -h|--help|help) usage; exit 0;;
  split)
    case "${2:-}" in -h|--help) usage; exit 0;; esac
    ;;
esac

# Activate inside this process, including PATH for fastp, Kraken2 and shell modules.
# shellcheck source=f/conda_env.sh
source "$METAG_ROOT/f/conda_env.sh"
metag_activate

case "${1:-}" in
  '') module=workflow.py;;
  split) shift; set -- --stage split "$@"; module=workflow.py;;
  prep_ref) shift; exec bash "$METAG_ROOT/f/prep_ref.sh" "$@";;
  --*)
    if [[ "$1" == --version ]]; then module=metag.py; else module=workflow.py; fi
    ;;
  build-db) shift; exec bash "$METAG_ROOT/f/build_db.sh" "$@";;
  reference-clean) shift; module=reference_cleanup.py;;
  datasets|prepare|pilot) module=datasets.py;;
  reference-urls) shift; module=reference_urls.py;;
  full)
    if [[ -n "${2:-}" && "${2:0:1}" != '-' ]]; then
      module=datasets.py
    else
      shift; exec bash "$METAG_ROOT/f/run_full.sh" "$@"
    fi
    ;;
  align) shift; exec bash "$METAG_ROOT/f/align_candidates.sh" "$@";;
  virus)
    shift
    if (($# == 0)); then set -- --help; fi
    module=virus_metadata.py
    ;;
  manifest|metadata-upgrade|organize|verify|db-audit|run|summary)
    module=metag.py
    ;;
  *) printf 'Unknown command: %s\n' "$1" >&2; usage >&2; exit 2;;
esac

command -v "$METAG_PYTHON" >/dev/null 2>&1 || {
  printf 'Python not found: %s. Check the metag environment or METAG_PYTHON setting.\n' "$METAG_PYTHON" >&2
  exit 127
}
exec "$METAG_PYTHON" "$METAG_ROOT/f/$module" "$@"
