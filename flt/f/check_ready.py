"""Read-only checks of starting inputs; never require previous FLT outputs."""
import os
import shutil
import sys
from pathlib import Path

from resources import inspect, allow_skips

errors, notes = [], []
if sys.version_info < (3, 10):
    errors.append("Python >= 3.10 is required; set FLT_PYTHON to the diet runtime.")


def require(path):
    path = Path(path)
    if not path.is_file() or path.stat().st_size == 0:
        errors.append(f"Missing/empty input: {path}")


ygb = Path(os.environ["FLT_YGB"])
for name in ("all", "icd10.code0", "icd10.date0", "diet.fudan", "prot"):
    require(ygb / "Rdata" / f"{name}.rds")
for name in ("flt", "icd10_brain", "cmd_anthropometry_lifestyle", "behavioral"):
    require(ygb / "common" / f"{name}.lst")
for name in ("flt", "cmd_anthropometry_lifestyle", "behavioral"):
    if not (ygb / "rap" / f"{name}.tab.gz").is_file():
        require(os.getenv("FLT_RAW", str(ygb / "rap/raw/pheno.tab.gz")))
for key in ("FLT_DICTIONARY", "FLT_MRI_DICTIONARY"):
    require(os.environ[key])
require(os.getenv("FLT_MRI_RAW", str(ygb / "rap/img.tab.gz")))
for resource, reason in inspect().items():
    if allow_skips():
        print(f"[SKIP RESOURCE] {resource}: {reason}")
    else:
        errors.append(reason)
ldsc = Path(os.getenv("FLT_LDSC_REF", str(Path(os.environ["FLT_LDREF"]) / "ldsc/hm3")))
require(ldsc / "w_hm3.snplist")
for chrom in range(1, 23):
    for suffix in (".l2.ldscore.gz", ".l2.M_5_50"):
        require(ldsc / f"{chrom}{suffix}")
for group in ("flt", "brain", "covs"):
    root = Path(os.environ["FLT_GWAS"]) / group
    if (root / "common").is_dir():
        root /= "common"
    if not root.is_dir() or not any(root.glob("*/gwas/*.gz")):
        errors.append(f"No GWAS inputs under: {root}")
for note in notes:
    print(note)
if errors:
    sys.exit("Starting input check failed (these are not generated by install.sh):\n  " + "\n  ".join(errors))
print("Starting input paths and executables passed; no previous analysis/flt outputs required.")
print("Input contents, model fits and online services are validated during the analysis.")
