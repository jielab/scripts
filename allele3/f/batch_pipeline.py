#!/usr/bin/env python3
"""Run one herv_pipeline stage inside an allocated batch_runner worker.

The argument parser is deliberately stdlib-only. Scientific imports, source
discovery, and payloads happen only after the worker/allocation guard. A selected
batch shares a read lock with other stage workers and excludes the legacy serial
pipeline. Each stage additionally has a cross-batch exclusive lock.

Example (normally generated by batch_workflows, not run on a login node)::

    batch_pipeline.py --stage primary --selected primary,report \
        --batch-id SHA256 --args-json '["pipeline", "--out", "/data/results"]'
"""
from __future__ import annotations

import argparse
from contextlib import contextmanager
import datetime as dt
import fcntl
import hashlib
import importlib
import json
import os
from pathlib import Path
import re
import shutil
import socket
import sys
import tempfile
import traceback


SCHEMA = "allele3-batch-stage-1"
SUCCESS = {"complete", "reused"}
TERMINAL = SUCCESS | {"failed", "not_available"}
STAGE_RE = re.compile(r"[a-z][a-z0-9_]*")
BATCH_RE = re.compile(r"[0-9a-f]{16,64}")


def now():
    return dt.datetime.now(dt.timezone.utc).isoformat()


def atomic_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, name = tempfile.mkstemp(prefix=path.name + ".", suffix=".partial", dir=path.parent)
    try:
        with os.fdopen(handle, "w") as stream:
            json.dump(value, stream, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


@contextmanager
def file_lock(path, *, shared=False, nonblocking=False):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as handle:
        flags = fcntl.LOCK_SH if shared else fcntl.LOCK_EX
        if nonblocking:
            flags |= fcntl.LOCK_NB
        try:
            fcntl.flock(handle, flags)
        except BlockingIOError:
            raise RuntimeError(f"Another pipeline worker owns {path}; no duplicate stage started") from None
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def worker_guard():
    if os.environ.get("ALLELE_BATCH_WORKER") != "1" or os.environ.get("WORKFLOW_WORKER") != "1":
        raise RuntimeError("Stage payload must be launched by batch_runner; use its .cmd/submit.sh interface")
    mode = os.environ.get("ALLELE_EXECUTION_MODE") or os.environ.get("submit") or os.environ.get("SUBMIT")
    if mode not in {"local", "hpc"}:
        raise RuntimeError("Worker execution mode must be local or hpc")
    allocated = re.fullmatch(r"[1-9][0-9]*", os.environ.get("LSB_JOBID", "")) is not None
    if mode == "hpc" and not allocated:
        raise RuntimeError("HPC stage payload requires an LSF allocation; it cannot execute on the login node")
    if mode == "local" and shutil.which("bsub") and not allocated:
        raise RuntimeError("Local stage payload refused on an LSF submission host without an allocation")


def load_pipeline():
    return importlib.import_module("herv_pipeline")


def audit_stage_sources(stage, argv):
    """Use actual single-stage paths, with bounded checks before any payload."""
    from data_sources import DEFAULT_CONFIG, audit_entries, load_config
    from workflow_data_check import actual_sources
    # argparse's last occurrence wins: retain the original argv unchanged and
    # narrow only this audit copy, even when the DAG requested many stages.
    entries, fasta37, fasta38 = actual_sources(stage, [*argv, "--stages", stage], load_config(DEFAULT_CONFIG))
    if not entries:
        return dict(has_conflicts=False, datasets=[], scope="no direct registered genomic inputs")
    return audit_entries(entries, out=None, fasta37=fasta37, fasta38=fasta38,
                         max_records=1000, max_sites=100)


def normalized_request(stage, selected, batch_id, argv, pipeline):
    if not isinstance(argv, list) or not all(isinstance(a, str) for a in argv):
        raise ValueError("--args-json must encode an array of original herv_pipeline argument strings")
    names = selected.split(",") if isinstance(selected, str) else list(selected)
    names = [name.strip() for name in names]
    if not names or len(names) != len(set(names)) or any(not STAGE_RE.fullmatch(name) for name in names):
        raise ValueError("--selected must contain unique, non-empty stage names")
    unknown = set(names) - set(pipeline.STAGES)
    if unknown or stage not in names or not STAGE_RE.fullmatch(stage):
        raise ValueError(f"Invalid stage selection: stage={stage}, unknown={sorted(unknown)}")
    names = [name for name in pipeline.STAGES if name in names]
    batch_id = batch_id.lower()
    if not BATCH_RE.fullmatch(batch_id):
        raise ValueError("--batch-id must be a 16-64 character hexadecimal SHA prefix")
    identity = hashlib.sha256(json.dumps(
        dict(schema=SCHEMA, args=argv, selected=names), sort_keys=True, separators=(",", ":")
    ).encode()).hexdigest()
    return names, batch_id, identity


def stage_record(out, batch_id, name, identity):
    path = out / ".batch_stage_status" / batch_id / (name + ".json")
    if not path.is_file():
        return None
    row = json.loads(path.read_text())
    if row.get("batch_id") != batch_id or row.get("args_identity") != identity or row.get("stage") != name:
        raise ValueError(f"Stage status identity differs from this batch: {path}")
    return row


def claim_batch(out, batch_id, identity, names, argv):
    """Called with the short owner lock held; a live batch retains its output."""
    path = out / ".batch_stage_owner.json"
    old = json.loads(path.read_text()) if path.exists() else None
    history = list(old.get("previous_batches", [])) if old else []
    if old and old.get("batch_id") == batch_id:
        if old.get("args_identity") != identity or old.get("selected") != names:
            raise ValueError("The same batch ID was used with different arguments/stages; create a new batch")
        return
    if batch_id in history:
        raise RuntimeError("This batch was superseded in this output directory; use its new batch or a new output")
    if old:
        unfinished = []
        for name in old["selected"]:
            row = stage_record(out, old["batch_id"], name, old["args_identity"])
            if row is None or row.get("status") not in TERMINAL:
                unfinished.append(name)
        if unfinished:
            raise RuntimeError(
                f"Output belongs to unfinished batch {old['batch_id']} ({','.join(unfinished)}); "
                "resume that batch or use a separate --out"
            )
        history.append(old["batch_id"])
    owner = dict(schema=SCHEMA, batch_id=batch_id, args_identity=identity, selected=names,
                 args=argv, claimed_at=now(), previous_batches=history)
    atomic_json(path, owner)
    atomic_json(out / ".batch_stage_status" / batch_id / "batch.json", owner)


def dependency_names(stage, selected, args):
    if stage == "report":
        return [name for name in selected if name != "report"]
    required = []
    if stage == "summary":
        required.append("archaic")
    if stage in {"time", "selection"} and not getattr(args, "allele_catalog", None):
        required.append("alleles")
    if stage == "genotypes" and not getattr(args, "targets", None):
        required.append("candidates")
    return [name for name in required if name in selected]


def check_dependencies(out, batch_id, identity, names):
    from batch_runner import validate_output_file
    for name in names:
        row = stage_record(out, batch_id, name, identity)
        if row is None or row.get("status") not in SUCCESS:
            status = row.get("status") if row else "not_started"
            raise RuntimeError(f"Dependency {name} is {status} in this batch; stale output is not reused")
        validate_output_file(out / ".batch_stage_status" / batch_id / (name + ".json"))


def scientific_validation(stage, step, receipts, pipeline, out, batch_id, required):
    """Bind the small stage ledger to the original scientific result receipt."""
    from batch_runner import STAGE_VALIDATION_SCHEMA, path_identity, validate_stage_receipt, verify_stat_identity
    result = dict(schema=STAGE_VALIDATION_SCHEMA, snapshot=pipeline.snapshot(step),
                  verification="file_size_mtime; no routine large-file content hashing",
                  dependencies=[path_identity(out / ".batch_stage_status" / batch_id / (name + ".json"))
                                for name in required])
    if stage == "report":
        result["outputs"] = [path_identity(out / "report.html")]
        for expected in result["outputs"]:
            verify_stat_identity(expected)
    else:
        receipt = receipts / (stage + ".json")
        result["receipt"] = path_identity(receipt)
        verify_stat_identity(result["receipt"])
        validate_stage_receipt(receipt, set())
    return result


def aggregate_status(out, batch_id, identity, names, configuration, pipeline, *, before_report=False):
    """Read only this batch; write under the short owner lock, never by execute()."""
    records = []
    for name in names:
        row = stage_record(out, batch_id, name, identity)
        if row is None:
            row = dict(stage=name, status="not_started", batch_id=batch_id, args_identity=identity)
        # The report renders this snapshot. As in the serial pipeline, do not
        # freeze its own temporary "running" row into a completed HTML report.
        if before_report and name == "report":
            continue
        records.append(row)
    statuses = {r["status"] for r in records}
    if "failed" in statuses:
        status = "failed"
    elif "not_available" in statuses:
        status = "partial_missing_inputs"
    elif statuses - SUCCESS:
        status = "running"
    else:
        status = pipeline.overall(records)
    result = dict(schema=SCHEMA, batch_id=batch_id, args_identity=identity, status=status,
                  stages=records, configuration=configuration, updated=now())
    atomic_json(out / "pipeline_status.json", result)
    atomic_json(out / ".batch_stage_status" / batch_id / "pipeline_status.json", result)
    return result


def run_stage_worker(stage, selected, batch_id, argv):
    worker_guard()
    pipeline = load_pipeline()
    names, batch_id, identity = normalized_request(stage, selected, batch_id, argv, pipeline)
    args = pipeline.parser().parse_args(argv)
    if getattr(args, "dry_run", False) or getattr(args, "preflight", False):
        raise ValueError("A stage payload cannot carry --dry-run/--preflight; use batch_runner --write-cmd")
    paths = pipeline.resolve(args)
    out = Path(paths["out"]).resolve()
    out.mkdir(parents=True, exist_ok=True)
    receipts = out / ".receipts"
    receipts.mkdir(exist_ok=True)
    configuration = {k: str(v) if isinstance(v, Path) else v for k, v in paths.items()}
    configuration.update(stages=names, version=pipeline.VERSION, batch_id=batch_id,
                         reuse="validated original stage input/parameter/output identities")
    record_path = out / ".batch_stage_status" / batch_id / (stage + ".json")
    control_lock = out / ".batch_stage_locks" / "owner.lock"
    # Shared legacy lock permits concurrent batch stages, but blocks the serial
    # execute() API's exclusive lock and protects this output from that API.
    with file_lock(out / ".pipeline.lock", shared=True, nonblocking=True), \
            file_lock(out / ".batch_stage_locks" / (stage + ".lock"), nonblocking=True):
        row = dict(schema=SCHEMA, batch_id=batch_id, args_identity=identity, selected=names,
                   stage=stage, status="running", started=pipeline.now(), host=socket.gethostname(),
                   pid=os.getpid(), lsf_job_id=os.environ.get("LSB_JOBID"))
        with file_lock(control_lock):
            claim_batch(out, batch_id, identity, names, argv)
            atomic_json(record_path, row)
        try:
            required = dependency_names(stage, names, args)
            check_dependencies(out, batch_id, identity, required)
            row["source_audit"] = audit_stage_sources(stage, argv)
            if row["source_audit"].get("has_conflicts"):
                raise ValueError("Conflicting source identities/builds; stage workload was not started")
            planned = pipeline.plan(args, paths, [stage])
            if len(planned) != 1 or planned[0].name != stage:
                raise RuntimeError("Original planner did not return the requested stage")
            step = planned[0]
            if stage == "time" and not any(pipeline.availability(step).values()):
                pipeline.prepare_metadata_if_needed(paths, receipts)
                if paths["metadata"] not in step.inputs:
                    step.inputs.append(paths["metadata"])
            if stage == "report":
                with file_lock(control_lock):
                    aggregate_status(out, batch_id, identity, names, configuration, pipeline, before_report=True)
            result = pipeline.run_stage(step, receipts, always=stage in {"report", "archaic"})
            if result.get("stage") != stage or result.get("status") not in TERMINAL:
                raise RuntimeError(f"Invalid terminal stage result: {result}")
            row.update(result)
            code = 0 if row["status"] in SUCCESS else 3 if row["status"] == "not_available" else 2
            if code == 0:
                row["scientific_validation"] = scientific_validation(stage, step, receipts, pipeline, out, batch_id, required)
        except Exception as exc:
            row.update(status="failed", reason=str(exc), error_type=type(exc).__name__)
            traceback.print_exc()
            code = 2
        row.setdefault("completed", pipeline.now())
        row["worker_exit_code"] = code
        with file_lock(control_lock):
            atomic_json(record_path, row)
            if stage == "report":
                aggregate_status(out, batch_id, identity, names, configuration, pipeline)
        print(f"[batch-stage] stage={stage} status={row['status']} batch={batch_id} receipt={record_path}", flush=True)
        return code


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--stage", required=True)
    p.add_argument("--selected", required=True, help="Comma-separated stage set in this exact DAG")
    p.add_argument("--batch-id", required=True, help="SHA256 identity or its 16-64 hex-character prefix")
    p.add_argument("--args-json", required=True, help="JSON array of original herv_pipeline arguments")
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    try:
        original = json.loads(args.args_json)
        return run_stage_worker(args.stage, args.selected, args.batch_id, original)
    except (OSError, ValueError, RuntimeError, KeyError, ImportError) as exc:
        print(f"batch-pipeline: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
