def pipeline_audit_stage_sources(stage, argv):
    """Use actual single-stage paths, with bounded checks before any payload."""
    from data_sources import DEFAULT_CONFIG, audit_entries, load_config
    from workflow_data_check import actual_sources
    # argparse's last occurrence wins: retain the original argv unchanged and
    # narrow only this audit copy, even when the DAG requested many stages.
    entries, fasta37, fasta38 = actual_sources(stage, [*argv, "--stages", stage], load_config(DEFAULT_CONFIG))
    if not entries:
        return dict(has_conflicts=False, datasets=[], scope="no direct registered genomic inputs")
    return audit_entries(entries, out=None, fasta37=fasta37, fasta38=fasta38,
                         max_records=1000, max_sites=100)


def pipeline_normalized_request(stage, selected, batch_id, argv, pipeline):
    if not isinstance(argv, list) or not all(isinstance(a, str) for a in argv):
        raise ValueError("--args-json must encode an array of original herv_pipeline argument strings")
    names = selected.split(",") if isinstance(selected, str) else list(selected)
    names = [name.strip() for name in names]
    if not names or len(names) != len(set(names)) or any(not PIPELINE_STAGE_RE.fullmatch(name) for name in names):
        raise ValueError("--selected must contain unique, non-empty stage names")
    unknown = set(names) - set(pipeline.STAGES)
    if unknown or stage not in names or not PIPELINE_STAGE_RE.fullmatch(stage):
        raise ValueError(f"Invalid stage selection: stage={stage}, unknown={sorted(unknown)}")
    names = [name for name in pipeline.STAGES if name in names]
    batch_id = batch_id.lower()
    if not PIPELINE_BATCH_RE.fullmatch(batch_id):
        raise ValueError("Invalid internal batch identifier")
    identity = hashlib.sha256(json.dumps(
        dict(schema=PIPELINE_SCHEMA, args=argv, selected=names), sort_keys=True, separators=(",", ":")
    ).encode()).hexdigest()
    return names, batch_id, identity


def pipeline_stage_record(out, batch_id, name, identity):
    path = (out / "qc/stages") / (name + ".json")
    if not path.is_file():
        return None
    row = json.loads(path.read_text())
    if row.get("batch_id") != batch_id or row.get("args_identity") != identity or row.get("stage") != name:
        raise ValueError(f"Stage status identity differs from this batch: {path}")
    return row


def pipeline_claim_batch(out, batch_id, identity, names, argv):
    """Called with the short owner lock held; a live batch retains its output."""
    path = out / ".batch_stage_owner.json"
    old = json.loads(path.read_text()) if path.exists() else None
    history = list(old.get("previous_batches", [])) if old else []
    if old and old.get("batch_id") == batch_id:
        if old.get("args_identity") != identity or old.get("selected") != names:
            raise ValueError("The same batch ID was used with different arguments/stages; create a new batch")
        return
    if batch_id in history:
        raise RuntimeError("This batch was superseded in this output directory; use its new batch or a new output")
    # The sequence/stage file locks, rather than stale owner metadata, exclude
    # live writers. An interrupted prior attempt must not block a fresh run.
    if old:
        history.append(old['batch_id'])
    owner = dict(schema=PIPELINE_SCHEMA, batch_id=batch_id, args_identity=identity, selected=names,
                 args=argv, claimed_at=pipeline_now(), previous_batches=history)
    pipeline_atomic_json(path, owner)
    pipeline_atomic_json((out / "qc/stages") / "batch.json", owner)


def pipeline_dependency_names(stage, selected, args):
    if stage == "report":
        return [name for name in selected if name != "report"]
    required = []
    if stage == "summary":
        required.append("archaic")
    if stage in {"time", "selection"} and not getattr(args, "allele_catalog", None):
        required.append("alleles")
    if stage == "genotypes" and not getattr(args, "targets", None):
        required.append("candidates")
    # Omitting a module runs the complete analysis in order. These are success
    # dependencies (done), not merely concurrency lanes (ended).
    if getattr(args, "command", "pipeline") == "pipeline" and not getattr(args, "stages", None):
        index = list(selected).index(stage)
        if index:
            required.append(selected[index - 1])
    return list(dict.fromkeys(name for name in required if name in selected))


def pipeline_check_dependencies(out, batch_id, identity, names):
    from batch_runner import validate_output_file
    for name in names:
        row = pipeline_stage_record(out, batch_id, name, identity)
        if row is None or row.get("status") not in PIPELINE_SUCCESS:
            status = row.get("status") if row else "not_started"
            raise RuntimeError(f"Dependency {name} is {status} in this batch; stale output is not reused")
        validate_output_file((out / "qc/stages") / (name + ".json"))


def pipeline_scientific_validation(stage, step, receipts, pipeline, out, batch_id, required):
    """Bind the small stage ledger to the original scientific result receipt."""
    from batch_runner import STAGE_VALIDATION_SCHEMA, path_identity, validate_stage_receipt, verify_stat_identity
    result = dict(schema=STAGE_VALIDATION_SCHEMA, snapshot=pipeline.snapshot(step),
                  verification="file_size_mtime; no routine large-file content hashing",
                  dependencies=[path_identity((out / "qc/stages") / (name + ".json"))
                                for name in required])
    if stage == "report":
        result["outputs"] = [path_identity(out / "reports/herv_enrichment.html")]
        for expected in result["outputs"]:
            verify_stat_identity(expected)
    else:
        receipt = receipts / (stage + ".json")
        result["receipt"] = path_identity(receipt)
        verify_stat_identity(result["receipt"])
        validate_stage_receipt(receipt, set())
    return result


def pipeline_aggregate_status(out, batch_id, identity, names, configuration, pipeline, *, before_report=False):
    """Read only this batch; write under the short owner lock, never by execute()."""
    records = []
    for name in names:
        row = pipeline_stage_record(out, batch_id, name, identity)
        if row is None:
            row = dict(stage=name, status="not_started", batch_id=batch_id, args_identity=identity)
        # The report renders this snapshot. As in the serial pipeline, do not
        # freeze its own temporary "running" row into a completed HTML report.
        if before_report and name == "report":
            continue
        records.append(row)
    statuses = {r["status"] for r in records}
    if "failed" in statuses:
        status = "failed"
    elif "not_available" in statuses:
        status = "partial_missing_inputs"
    elif statuses - PIPELINE_SUCCESS:
        status = "running"
    else:
        status = pipeline.overall(records)
    result = dict(schema=PIPELINE_SCHEMA, batch_id=batch_id, args_identity=identity, status=status,
                  stages=records, configuration=configuration, updated=pipeline_now())
    pipeline_atomic_json(out / "qc/pipeline_status.json", result)
    pipeline_atomic_json((out / "qc/stages") / "pipeline_status.json", result)
    return result


def pipeline_run_stage_worker(stage, selected, batch_id, argv, *, _sequence_lock_held=False):
    pipeline_worker_guard()
    pipeline = pipeline_load_pipeline()
    names, batch_id, identity = pipeline_normalized_request(stage, selected, batch_id, argv, pipeline)
    args = pipeline.parser().parse_args(argv)
    if getattr(args, "dry_run", False) or getattr(args, "preflight", False):
        raise ValueError("A stage payload cannot carry --dry-run/--preflight; use batch_runner --write-cmd")
    paths = pipeline.resolve(args)
    out = Path(paths["out"]).resolve()
    out.mkdir(parents=True, exist_ok=True)
    receipts = out / "qc/receipts"
    receipts.mkdir(parents=True, exist_ok=True)
    configuration = {k: str(v) if isinstance(v, Path) else v for k, v in paths.items()}
    configuration.update(stages=names, version=pipeline.VERSION, batch_id=batch_id,
                         ibdmix_enabled=getattr(args, "ibdmix", False),
                         disabled_stages=[] if getattr(args, "ibdmix", False) else ["archaic"],
                         reuse="validated original stage input/parameter/output identities")
    record_path = (out / "qc/stages") / (stage + ".json")
    control_lock = out / "qc/locks" / "owner.lock"
    # Shared legacy lock permits concurrent batch stages, but blocks the serial
    # execute() API's exclusive lock and protects this output from that API.
    lock = nullcontext() if _sequence_lock_held else pipeline_file_lock(out / "qc/pipeline.lock", shared=True, nonblocking=True)
    with lock, \
            pipeline_file_lock(out / "qc/locks" / (stage + ".lock"), nonblocking=True):
        row = dict(schema=PIPELINE_SCHEMA, batch_id=batch_id, args_identity=identity, selected=names,
                   stage=stage, status="running", started=pipeline.now(), host=socket.gethostname(),
                   pid=os.getpid(), lsf_job_id=os.environ.get("LSB_JOBID"))
        with pipeline_file_lock(control_lock):
            pipeline_claim_batch(out, batch_id, identity, names, argv)
            pipeline_atomic_json(record_path, row)
            if _sequence_lock_held:
                pipeline_aggregate_status(out, batch_id, identity, names, configuration, pipeline)
        try:
            required = pipeline_dependency_names(stage, names, args)
            pipeline_check_dependencies(out, batch_id, identity, required)
            row["source_audit"] = pipeline_audit_stage_sources(stage, argv)
            if row["source_audit"].get("has_conflicts"):
                raise ValueError("Conflicting source identities/builds; stage workload was not started")
            planned = pipeline.plan(args, paths, [stage])
            if len(planned) != 1 or planned[0].name != stage:
                raise RuntimeError("Original planner did not return the requested stage")
            step = planned[0]
            if stage == "time" and not any(pipeline.availability(step).values()):
                pipeline.prepare_metadata_if_needed(paths, receipts)
                if paths["metadata"] not in step.inputs:
                    step.inputs.append(paths["metadata"])
            if stage == "report":
                with pipeline_file_lock(control_lock):
                    pipeline_aggregate_status(out, batch_id, identity, names, configuration, pipeline, before_report=True)
            result = pipeline.run_stage(step, receipts, always=stage in {"report", "archaic"})
            if result.get("stage") != stage or result.get("status") not in PIPELINE_TERMINAL:
                raise RuntimeError(f"Invalid terminal stage result: {result}")
            row.update(result)
            code = 0 if row["status"] in PIPELINE_SUCCESS else 3 if row["status"] == "not_available" else 2
            if code == 0:
                row["scientific_validation"] = pipeline_scientific_validation(stage, step, receipts, pipeline, out, batch_id, required)
        except Exception as exc:
            row.update(status="failed", reason=str(exc), error_type=type(exc).__name__)
            traceback.print_exc()
            code = 2
        row.setdefault("completed", pipeline.now())
        row["worker_exit_code"] = code
        with pipeline_file_lock(control_lock):
            pipeline_atomic_json(record_path, row)
            if stage == "report" or _sequence_lock_held:
                pipeline_aggregate_status(out, batch_id, identity, names, configuration, pipeline)
        print(f"[batch-stage] stage={stage} status={row['status']} batch={batch_id} receipt={record_path}", flush=True)
        return code


def pipeline_run_sequence_worker(selected, batch_id, argv):
    """One allocation, success-only sequencing, original per-stage receipts."""
    pipeline_worker_guard()
    pipeline = pipeline_load_pipeline()
    first = selected.split(",")[0] if isinstance(selected, str) else selected[0]
    names, batch_id, identity = pipeline_normalized_request(first, selected, batch_id, argv, pipeline)
    args = pipeline.parser().parse_args(argv)
    out = Path(pipeline.resolve(args)["out"]).resolve()
    # Hold this across module boundaries, excluding both another sequence and
    # individually submitted stages that target the same output directory.
    with pipeline_file_lock(out / "qc/pipeline.lock", nonblocking=True):
        print("[batch-sequence] " + " -> ".join(names), flush=True)
        for index, name in enumerate(names):
            code = pipeline_run_stage_worker(name, names, batch_id, argv, _sequence_lock_held=True)
            if code:
                # This allocation has stopped. Close the unstarted modules so
                # a corrected plan can take over without an unfinished owner;
                # never turn their old products into successful current results.
                with pipeline_file_lock(out / "qc/locks" / "owner.lock"):
                    configuration = json.loads((out / "qc/pipeline_status.json").read_text())["configuration"]
                    for blocked in names[index + 1:]:
                        row = dict(schema=PIPELINE_SCHEMA, batch_id=batch_id, args_identity=identity,
                                   selected=names, stage=blocked, status="not_available",
                                   blocked_by=name, reason="previous module failed; not executed in this attempt",
                                   completed=pipeline.now(), worker_exit_code=code,
                                   lsf_job_id=os.environ.get("LSB_JOBID"))
                        pipeline_atomic_json((out / "qc/stages") / (blocked + ".json"), row)
                    pipeline_aggregate_status(out, batch_id, identity, names, configuration, pipeline)
                print(f"[batch-sequence] stopped at {name}; later modules were not started", flush=True)
                return code
    return 0


def pipeline_parser():
    p = argparse.ArgumentParser(description=_description_batch_pipeline)
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--stage")
    mode.add_argument("--all-stages", action="store_true", help="Run selected modules sequentially in this allocation")
    p.add_argument("--selected", required=True, help="Comma-separated selected stage set")
    p.add_argument("--batch-id", required=True, help="Internal invocation identifier")
    p.add_argument("--args-json", required=True, help="JSON array of original herv_pipeline arguments")
    return p


def pipeline_main(argv=None):
    args = pipeline_parser().parse_args(argv)
    try:
        original = json.loads(args.args_json)
        if args.all_stages:
            return pipeline_run_sequence_worker(args.selected, args.batch_id, original)
        return pipeline_run_stage_worker(args.stage, args.selected, args.batch_id, original)
    except (OSError, ValueError, RuntimeError, KeyError, ImportError) as exc:
        print(f"batch-pipeline: {exc}", file=sys.stderr)
        return 2


