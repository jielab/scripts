def bind_atlas_inputs(plan,args):
    """Bind default and configured source identities without opening the atlas.

    Only the small resource descriptor is read on the submission host. Index
    discovery records both potential companions if none was explicitly chosen,
    so a later replacement or additional index changes the frozen plan.
    """
    from atlas_scores import load_resources, default_resources, resource_input_paths
    atlas_data=getattr(args,'dir_data',None) or env_paths()[0]
    descriptor=Path(args.atlas_resources or default_resources(atlas_data)).expanduser().resolve()
    # Freeze the automatic storage choice, so worker and planner use one schema.
    args.atlas_resources=str(descriptor)
    specs=load_resources(argparse.Namespace(resources=str(descriptor),dir_data=atlas_data,
        avi_file=args.avi_file,avi_index=args.avi_index,source_version=args.atlas_source_version,
        targets=args.targets,max_targets=args.max_targets,
        chromosomes=getattr(args,'chromosomes','all'),region=getattr(args,'region',None),
        require_all_resources=getattr(args,'require_all_resources',False)))
    if not Path(args.targets).expanduser().is_file():
        raise ValueError('Required Atlas targets file missing: '+absolute(args.targets))
    plan['inputs'].append(dict(path=absolute(descriptor),sha256=True))
    plan['inputs'] += sorted({path for row in specs for path in resource_input_paths(row)})


def bind_derivative_input(plan, value, module, flag):
    """Bind file metadata, not a directory's misleading missing-file identity.

    No payload is decoded. Directory analyses bind the files they consume;
    execution logs and submission ledgers do not invalidate scientific reuse.
    """
    from analysis_integrity import resolve_result_input
    path=Path(resolve_result_input(value)).expanduser()
    if not path.is_dir():
        plan['inputs'].append(dict(path=absolute(path),sha256=False))
        return
    if module=='review' and flag=='--analysis-dir':
        relatives=[
            'gnomad_scan/results/occupancy_thresholds.tsv',
            'gnomad_scan/results/singleton_sensitivity.tsv',
            'hotspots/results/windows.nominated_windows.tsv',
            'hotspots/results/characterize.selected_windows.tsv',
            'hotspots/results/characterize.window_matches.tsv',
            'hotspots/results/characterize.annotation_contrasts.tsv',
            'hotspots/results/impact.window_atlas_summary.tsv',
            'hotspots/results/selection.window_selection_summary.tsv',
            'assoc/reports/index.html']
        paths=[path/rel for rel in relatives]
    elif module=='cohort' and flag=='--census-root':
        paths=[p for name in ('run.json','analysis.done.json','genome_fraction.json','genome_fraction.tsv') for p in path.rglob(name)]
    else:
        excluded={'jobs','logs','tmp','history','locks','__pycache__'}
        paths=[p for p in path.rglob('*') if p.is_file() and not (set(p.relative_to(path).parts)&excluded)]
    plan['inputs'] += [dict(path=absolute(p),sha256=False) for p in sorted(set(paths))]


